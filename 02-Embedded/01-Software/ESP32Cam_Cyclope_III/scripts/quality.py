#!/usr/bin/env python3
"""Small, dependency-free wrappers around Arduino CLI and cppcheck."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SKETCH = ROOT / "esp32_s3_ai_camera_vv"
BUILD = ROOT / ".build"
HEADER = SKETCH / "firmware_version.h"


def version_text():
    version = (ROOT / "VERSION").read_text().strip()
    if not re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", version):
        raise ValueError("VERSION must contain one semantic MAJOR.MINOR.PATCH version")
    return version


def generated_header():
    return ("// Generated from ../VERSION by scripts/quality.py version --write.\n"
            "// Do not edit this file directly.\n#pragma once\n"
            f'#define CYCLOPE_FIRMWARE_VERSION "{version_text()}"\n')


def check_version(write=False):
    expected = generated_header()
    if write:
        HEADER.write_text(expected)
    if not HEADER.exists() or HEADER.read_text() != expected:
        raise ValueError("Version drift: run python3 scripts/quality.py version --write")
    print(f"Version verified: {version_text()}", flush=True)


def configuration():
    return json.loads((ROOT / "toolchain.json").read_text())


def install():
    config = configuration()
    subprocess.run(["arduino-cli", "core", "update-index", "--additional-urls",
                    config["index_url"]], check=True)
    subprocess.run(["arduino-cli", "core", "install",
                    f'{config["core"]}@{config["core_version"]}',
                    "--additional-urls", config["index_url"]], check=True)


def compile_firmware():
    check_version()
    config = configuration()
    cores = json.loads(subprocess.check_output(["arduino-cli", "core", "list", "--json"]))
    installed = {p["id"]: p.get("installed_version") for p in cores.get("platforms", [])}
    if installed.get(config["core"]) != config["core_version"]:
        raise ValueError("Pinned core not installed: run python3 scripts/quality.py install")
    output = BUILD / "firmware"
    output.mkdir(parents=True, exist_ok=True)
    command = ["arduino-cli", "compile", "--fqbn", config["fqbn"],
               "--jobs", str(config["jobs"]), "--warnings", "all",
               "--build-path", str(BUILD / "cache"), "--output-dir", str(output),
               "--build-property", f'compiler.cpp.extra_flags=-include "{HEADER}"', str(SKETCH)]
    print(f'Compile gate: core={config["core"]}@{config["core_version"]}; fqbn={config["fqbn"]}', flush=True)
    subprocess.run(command, check=True)
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    info = {"firmware_version": version_text(), "git_commit": commit,
            "source_dirty": bool(subprocess.check_output(
                ["git", "status", "--porcelain", "--untracked-files=normal", "--", "."], cwd=ROOT)),
            "sketch_sha256": hashlib.sha256((SKETCH / "esp32_s3_ai_camera_vv.ino").read_bytes()).hexdigest(),
            "core": config["core"], "core_version": config["core_version"], "fqbn": config["fqbn"],
            "arduino_cli": subprocess.check_output(["arduino-cli", "version"], text=True).strip()}
    (output / "version.json").write_text(json.dumps(info, indent=2) + "\n")


def cppcheck():
    reports = BUILD / "reports"
    reports.mkdir(parents=True, exist_ok=True)
    command = ["cppcheck", "--enable=warning,style,performance,portability", "--inconclusive",
               "--std=c++17", "--language=c++", "--platform=unix32",
               "--suppress=missingIncludeSystem", "--error-exitcode=1", "--xml", "--xml-version=2",
               str(SKETCH / "esp32_s3_ai_camera_vv.ino")]
    result = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    (reports / "cppcheck.xml").write_text(result.stderr)
    errors = ET.fromstring(result.stderr).findall("./errors/error")
    lines = [subprocess.check_output(["cppcheck", "--version"], text=True).strip(),
             "Profile: warning/style/performance/portability + inconclusive; unix32; C++17.",
             "Scope: sketch only, no ESP32 SDK headers; no runtime/hardware verification.",
             f"Exit code: {result.returncode}; findings: {len(errors)}"]
    for error in errors:
        location = error.find("location")
        at = f'{location.get("file")}:{location.get("line")}' if location is not None else "unknown"
        lines.append(f'{at}: {error.get("severity")} [{error.get("id")}]: {error.get("msg")}')
    report = "\n".join(lines) + "\n"
    (reports / "cppcheck.txt").write_text(report)
    print(report, end="")
    return result.returncode


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    version = sub.add_parser("version", help="check the generated version header")
    version.add_argument("--write", action="store_true", help="regenerate the header after editing VERSION")
    sub.add_parser("install", help="install the pinned official ESP32 Arduino core")
    sub.add_parser("compile", help="verify version and compile without uploading to hardware")
    sub.add_parser("cppcheck", help="produce static-analysis reports (exit 1 for findings)")
    args = parser.parse_args()
    if args.command == "version":
        check_version(args.write)
    elif args.command == "install":
        install()
    elif args.command == "compile":
        compile_firmware()
    elif args.command == "cppcheck":
        return cppcheck()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError, ET.ParseError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(2)
